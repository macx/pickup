#!/bin/bash
# Builds App/.build/Pickup.app (debug by default; pass "release" for a release build).
# XcodeGen is not installed, so this wraps the SwiftPM executable into a signed app bundle.
#
#   scripts/build-app.sh            debug build, ad-hoc signed, test hooks compiled in (unchanged dev behaviour)
#   scripts/build-app.sh release    release build: version stamped from VERSION (scripts/set-version.sh), Hardened
#                                   Runtime, App/Pickup-Release.entitlements, signed inside-out, audited afterwards
#
# Release signing (docs/RELEASING.md):
#   PICKUP_SIGN_IDENTITY   "Developer ID Application: <Name> (<TEAMID>)" or its SHA-1 hash. Required for release,
#                          unless PICKUP_ADHOC_RELEASE=1.
#   PICKUP_KEYCHAIN        optional keychain that holds the identity (CI uses a temporary keychain).
#   PICKUP_ADHOC_RELEASE=1 dry run without a certificate: release build, ad-hoc signed ("-"), no timestamp. Such a
#                          bundle cannot pass Gatekeeper and must never be shipped (package-release.sh names it
#                          *-UNSIGNED).
#   PICKUP_VERSION / PICKUP_BUILD_NUMBER   override the version stamped into the bundle (see set-version.sh).
#
# Gate (docs/TESTING.md): no app bundle unless scripts/verify.sh passed for this exact tree (it is a no-op when
# .build/verify-stamp matches). PICKUP_SKIP_VERIFY=1 skips it for quick local builds and for ad-hoc release dry
# runs, never for a release signed with a real identity. PICKUP_GATE=ci (only honoured inside GitHub Actions)
# tells the release workflow's build step that the same workflow run already passed every CI job (`needs:`).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONFIG="${1:-debug}"
case "$CONFIG" in debug|release) ;; *) echo "build-app: unknown configuration '$CONFIG' (debug or release)" >&2; exit 2 ;; esac

die() { echo "build-app: $*" >&2; exit 1; }

# --- Signing mode -------------------------------------------------------------------------------
SIGN_MODE=dev
if [ "$CONFIG" = "release" ]; then
  if [ -n "${PICKUP_SIGN_IDENTITY:-}" ]; then
    SIGN_MODE=developer-id
  elif [ "${PICKUP_ADHOC_RELEASE:-0}" = "1" ]; then
    SIGN_MODE=adhoc-release
  else
    die "release builds need PICKUP_SIGN_IDENTITY (\"Developer ID Application: ...\"); for an unsigned dry run set PICKUP_ADHOC_RELEASE=1"
  fi
fi

# --- Gate ---------------------------------------------------------------------------------------
if [ "$CONFIG" = "release" ]; then
  if [ "${PICKUP_GATE:-}" = "ci" ] && [ "${GITHUB_ACTIONS:-}" = "true" ]; then
    echo "build-app: gate enforced by the CI jobs this workflow run depends on (PICKUP_GATE=ci); not repeating verify.sh."
  elif [ "${PICKUP_SKIP_VERIFY:-0}" = "1" ]; then
    [ "$SIGN_MODE" = "adhoc-release" ] || die "PICKUP_SKIP_VERIFY=1 is refused for a release signed with a real identity; run the gate"
    echo "WARNING: PICKUP_SKIP_VERIFY=1 -- ad-hoc release dry run WITHOUT the verification gate. Never ship this build." >&2
  else
    "$ROOT/scripts/verify.sh" --release
  fi
elif [ "${PICKUP_SKIP_VERIFY:-0}" = "1" ]; then
  echo "WARNING: PICKUP_SKIP_VERIFY=1 -- building WITHOUT the verification gate. Do not ship or commit based on this build." >&2
else
  "$ROOT/scripts/verify.sh"
fi

cd "$ROOT/App"
swift build -c "$CONFIG"
BIN="$(swift build -c "$CONFIG" --show-bin-path)"
APP=".build/Pickup.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN/Pickup" "$APP/Contents/MacOS/Pickup"
cp Info.plist "$APP/Contents/Info.plist"
# Compile String Catalogs to .lproj/*.strings
for catalog in Resources/*.xcstrings; do
  xcrun xcstringstool compile "$catalog" --output-directory "$APP/Contents/Resources"
done
# App icon (Icon Composer .icon -> Assets.car + Pickup.icns); regenerate layers with scripts/generate-app-icon.swift
# (absolute paths: actool resolves relative ones against odd directories)
ICON_PLIST="$(mktemp)"
xcrun actool "$(pwd)/Resources/Pickup.icon" --compile "$(pwd)/$APP/Contents/Resources" --app-icon Pickup \
  --platform macosx --minimum-deployment-target 26.0 --target-device mac \
  --output-partial-info-plist "$ICON_PLIST" >/dev/null
rm -f "$ICON_PLIST"
# Menu bar template images (vector PDFs, generated by scripts/generate-app-icon.swift)
cp Resources/MenuBar/*.pdf "$APP/Contents/Resources/"

if [ "$CONFIG" = "debug" ]; then
  # Ad-hoc signing (development only). PICKUP_NO_SANDBOX=1 drops the App Sandbox, which is required
  # for "Make Pickup the default for phone links" to work (see App/Pickup-NoSandbox.entitlements).
  ENTITLEMENTS=Pickup.entitlements
  [ "${PICKUP_NO_SANDBOX:-0}" = "1" ] && ENTITLEMENTS=Pickup-NoSandbox.entitlements
  codesign --force --sign - --entitlements "$ENTITLEMENTS" --options runtime "$APP"
  echo "Entitlements: $ENTITLEMENTS"
  echo "Built $(pwd)/$APP"
  exit 0
fi

# --- Release ------------------------------------------------------------------------------------
# 1. Test hooks are compiled out of release builds (PICKUP_TESTING is debug-only in App/Package.swift); prove it.
if strings "$APP/Contents/MacOS/Pickup" | grep -E "PickupTestScenario|ScriptedTransport|dev\.eiken\.pickup\.test\." >/dev/null; then
  die "the release binary contains test-hook strings (PickupTestScenario/ScriptedTransport); check App/Package.swift"
fi

# 2. Version from VERSION (or PICKUP_VERSION / PICKUP_BUILD_NUMBER).
"$ROOT/scripts/set-version.sh" --apply "$(pwd)/$APP"

# 3. Sign inside-out: nested code first (deepest path first), then the app. Never `codesign --deep` for signing:
#    it applies the app's entitlements to every nested binary. Pickup has no nested code today; the loop keeps
#    future frameworks, XPC services, login items or helpers correct.
ENTITLEMENTS="$(pwd)/Pickup-Release.entitlements"
[ -f "$ENTITLEMENTS" ] || die "missing $ENTITLEMENTS"
SIGN_ARGS=(--force --options runtime)
if [ "$SIGN_MODE" = "developer-id" ]; then
  case "$PICKUP_SIGN_IDENTITY" in
    "Developer ID Application:"*|[0-9A-Fa-f][0-9A-Fa-f][0-9A-Fa-f][0-9A-Fa-f][0-9A-Fa-f][0-9A-Fa-f][0-9A-Fa-f][0-9A-Fa-f]*) ;;
    *) die "PICKUP_SIGN_IDENTITY must be a 'Developer ID Application: ...' identity (or its SHA-1); got '$PICKUP_SIGN_IDENTITY'" ;;
  esac
  SIGN_ARGS+=(--sign "$PICKUP_SIGN_IDENTITY" --timestamp)
  [ -n "${PICKUP_KEYCHAIN:-}" ] && SIGN_ARGS+=(--keychain "$PICKUP_KEYCHAIN")
else
  SIGN_ARGS+=(--sign - --timestamp=none)
fi

while IFS= read -r -d '' nested; do
  echo "build-app: signing nested code ${nested#"$APP"/}"
  codesign "${SIGN_ARGS[@]}" "$nested" || die "signing failed for $nested"
done < <(find "$APP/Contents" -depth -mindepth 2 \
           \( -name '*.framework' -o -name '*.dylib' -o -name '*.xpc' -o -name '*.appex' -o -name '*.app' \
              -o -name '*.bundle' -o -name '*.systemextension' \) -print0)
# Loose helper executables next to the main binary.
while IFS= read -r -d '' helper; do
  echo "build-app: signing helper ${helper#"$APP"/}"
  codesign "${SIGN_ARGS[@]}" "$helper" || die "signing failed for $helper"
done < <(find "$APP/Contents/MacOS" -type f -perm -u+x ! -name Pickup -print0)

codesign "${SIGN_ARGS[@]}" --entitlements "$ENTITLEMENTS" "$APP" \
  || die "signing the app failed (identity '${PICKUP_SIGN_IDENTITY:--}'; list identities with: security find-identity -v -p codesigning)"
codesign --verify --deep --strict --verbose=2 "$APP" || die "codesign --verify --deep --strict failed"

echo "Entitlements: Pickup-Release.entitlements"
echo "Signing: $SIGN_MODE${PICKUP_SIGN_IDENTITY:+ ($PICKUP_SIGN_IDENTITY)}"
echo "Built $(pwd)/$APP"

# 4. Audit the bundle that was just built (hardened runtime, entitlements, not debuggable, linked libraries).
"$ROOT/scripts/security-checks.sh" --release --strict --app "$(pwd)/$APP"
